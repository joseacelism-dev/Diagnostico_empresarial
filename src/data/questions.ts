function q(
  id: string,
  areaId: Question['areaId'],
  text: string,
  help: string,
  weight: 1 | 2 | 3,
  action: string,
  justification: string,
  tool: string,
  doc: string,
  responsible: string,
  priority: 'Alta' | 'Media' | 'Baja',
  months: '1-3' | '3-6' | '6-12',
  showIf?: (info: CompanyInfo, ans: Record<string, number>) => boolean,
): Question {
  return { id, areaId, text, help, weight, scale: QUESTION_SCALES[id] ?? 'maturity', showIf, rec: { action, justification, tool, doc, responsible, priority, months } };
}

